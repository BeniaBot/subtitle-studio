                    sb.Append(" · ").Append(t.ParamLabel).Append(": מספר ").Append(Num(t.Min)).Append("-").Append(Num(t.Max))
                      .Append(t.Suffix.Length > 0 ? " " + t.Suffix.Trim() : "").Append(", ברירת מחדל ").Append(Num(t.Def));
